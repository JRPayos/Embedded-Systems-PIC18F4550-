;================================INTERRUPT1=====================================    
INT1_ISR:
    ; Button press ISR (with debouncing)
    MOVF DEBOUNCE_FLAG, W    ; Check if debounce is active
    BTFSC STATUS, Z          ; If DEBOUNCE_FLAG == 0, process the button press
    BRA DEBOUNCE_ACTIVE     ; Skip processing if debounce is active

    ; Handle button press
    BTG MAIN_CTL, 0x1, ACCESS ; Toggle the MAIN_CTL bit to change sequence
    BSF DEBOUNCE_FLAG, 0      ; Set debounce flag

    ; Start debounce timer
    MOVLW 0x00
    MOVWF TMR0H, ACCESS       ; Reset Timer0 high byte
    MOVLW 0x00
    MOVWF TMR0L, ACCESS       ; Reset Timer0 low byte
    BSF T0CON, TMR0ON, ACCESS ; Enable Timer0

    BCF INTCON3, INT1IF, ACCESS ; Clear INT0 interrupt flag
    RETURN

DEBOUNCE_ACTIVE:
    BCF INTCON3, INT1IF, ACCESS ; Clear INT0 interrupt flag
    RETURN
    
    
