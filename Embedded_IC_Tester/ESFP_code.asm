HISR:
    ;High Prioity ISR
    BTFSC PIR1, RCIF, ACCESS
    RCALL RC_ISR
    BTFSC INTCON, INT0IF, ACCESS
    RCALL INT0_ISR
    BTFSC INTCON3, INT1IF, ACCESS
