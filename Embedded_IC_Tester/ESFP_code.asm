;===================================IC SELECT===================================
;1111111111111111111111111111111111111=NOT=1111111111111111111111111111111111111
NOT_04_INIT:
    ;NOT GATE I/O INIT CONFIGS B and D
    MOVLW 0x6B
    MOVWF TRISB, ACCESS	; SET RB[0,1,3,5,6] as INPUT; RB[2,4,7] as OUT 
    
    
    MOVLW 0x2A
    MOVWF TRISD, ACCESS	; SET RD[1,3,5] as INPUT; RD[0,2,4] as OUT 
      
NOT_04:    
    BTFSC MAIN_CTL, 0x1, ACCESS	    ;FOR CHANGE SEQ/CLR
    BRA AND_08_INIT			    ;JUMP to /NEXT/ IC_INIT
    
    BTFSC MAIN_CTL, 0x0, ACCESS	    ;FOR LOOP
    BRA NOT_04			    ;LOOP TO /SELF/
    
    MOVLW 0X04			    ;OUTPUT INDICATOR
    MOVWF LATA, ACCESS
    
    BTFSC MAIN_CTL, 0x1, ACCESS	    ;FOR CHANGE SEQ/CLR
    BRA AND_08_INIT
    
    BCF MAIN_CTL, 0x1, ACCESS	    ;DISABLE CHANGE SEQ/ UNLESS INT1 IS PRESSED
    BSF MAIN_CTL, 0x0, ACCESS	    ;TO LOOP BACK
    BRA NOT_04			    ;LOOP TO /SELF/
;22222222222222222222222222222222222=AND=222222222222222222222222222222222222222
AND_08_INIT:
    ;AND GATE I/O INIT CONFIGS B and D
    MOVLW 0x53
    MOVWF TRISB, ACCESS	; SET RB[|0,1|,4,6] as INPUT; RB[2,3,5,7] as OUT 
    
    MOVLW 0x24
    MOVWF TRISD, ACCESS	; SET RD[2,5] as INPUT; RD[0,1,3,4] as OUT 

AND_08:
    
    BTFSS MAIN_CTL, 0x1, ACCESS	    ;FOR CHANGE SEQ/SET
    BRA OR_32_INIT
    
    BTFSS MAIN_CTL, 0x0, ACCESS	    ;FOR LOOP
    BRA AND_08
    
    MOVLW 0X08
    MOVWF LATA, ACCESS
    
    BTFSS MAIN_CTL, 0x1, ACCESS	    ;FOR CHANGE SEQ/SET
    BRA OR_32_INIT
    
    BSF MAIN_CTL, 0x1, ACCESS	    ;DISABLE CHANGE SEQ/ UNLESS INT1 IS PRESSED
    BCF MAIN_CTL, 0x0, ACCESS	    ;TO LOOP BACK
    BRA AND_08
;333333333333333333333333333333333333=OR=333333333333333333333333333333333333333
OR_32_INIT:
    MOVLW 0x53
    MOVWF TRISB, ACCESS	; SET RB[|0,1|,4,6] as INPUT; RB[2,3,5,7] as OUT 
    MOVLW 0x24
    MOVWF TRISD, ACCESS	; SET RD[2,5] as INPUT; RD[0,1,3,4] as OUT    
OR_32:
    BTFSC MAIN_CTL, 0x1, ACCESS	    ;FOR CHANGE SEQ/CLR
    BRA NAND_00_INIT			    ;JUMP to /NEXT/ IC_INIT
    
    BTFSC MAIN_CTL, 0x0, ACCESS	    ;FOR LOOP
    BRA OR_32			    ;LOOP TO /SELF/
    
    MOVLW 0X0C			    ;OUTPUT INDICATOR
    MOVWF LATA, ACCESS
    
    BTFSC MAIN_CTL, 0x1, ACCESS	    ;FOR CHANGE SEQ/CLR
    BRA NAND_00_INIT
    
    BCF MAIN_CTL, 0x1, ACCESS	    ;DISABLE CHANGE SEQ/ UNLESS INT1 IS PRESSED
    BSF MAIN_CTL, 0x0, ACCESS	    ;TO LOOP BACK
    BRA OR_32			    ;LOOP TO /SELF/
;44444444444444444444444444444444444=NAND=44444444444444444444444444444444444444
NAND_00_INIT:
    MOVLW 0x53
    MOVWF TRISB, ACCESS	; SET RB[|0,1|,4,6] as INPUT; RB[2,3,5,7] as OUT     
    MOVLW 0x24
    MOVWF TRISD, ACCESS	; SET RD[2,5] as INPUT; RD[0,1,3,4] as OUT 
NAND_00:
    BTFSS MAIN_CTL, 0x1, ACCESS	    ;FOR CHANGE SEQ/SET
    BRA XOR_86_INIT
    
    BTFSS MAIN_CTL, 0x0, ACCESS	    ;FOR LOOP
    BRA NAND_00
    
    MOVLW 0X10
    MOVWF LATA, ACCESS
    
    BTFSS MAIN_CTL, 0x1, ACCESS	    ;FOR CHANGE SEQ/SET
    BRA XOR_86_INIT
    
    BSF MAIN_CTL, 0x1, ACCESS	    ;DISABLE CHANGE SEQ/ UNLESS INT1 IS PRESSED
    BCF MAIN_CTL, 0x0, ACCESS	    ;TO LOOP BACK
    BRA NAND_00
;5555555555555555555555555555555555555=XOR=5555555555555555555555555555555555555
XOR_86_INIT:
    MOVLW 0x53
    MOVWF TRISB, ACCESS
    MOVLW 0x24
    MOVWF TRISD, ACCESS
XOR_86:
    BTFSC MAIN_CTL, 0x1, ACCESS	    ;FOR CHANGE SEQ/CLR
    BRA NOR_02_INIT		    
    
    BTFSC MAIN_CTL, 0x0, ACCESS	    ;FOR LOOP
    BRA XOR_86			    ;LOOP TO /SELF/
    
    MOVLW 0X14			    
    MOVWF LATA, ACCESS
    
    BTFSC MAIN_CTL, 0x1, ACCESS	    ;FOR CHANGE SEQ/CLR
    BRA NOR_02_INIT
    
    BCF MAIN_CTL, 0x1, ACCESS	    
    BSF MAIN_CTL, 0x0, ACCESS	    
    BRA XOR_86			    
;666666666666666666666666666666666=NOR=66666666666666666666666666666666666666666    
